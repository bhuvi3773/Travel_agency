export function getPackageBySlug(slug: string) {
  return packages.find((p) => p.slug === slug);
}

export function getPackagesByDestination(destinationSlug: string) {
  return packages.filter((p) => p.destinationSlug === destinationSlug);
}

export function getFeaturedPackages(limit = 3) {
  return packages.filter((p) => p.featured).slice(0, limit);
}

export function getRelatedPackages(packageSlug: string, limit = 3) {
  const current = getPackageBySlug(packageSlug);
  if (!current) return [];
  return packages
    .filter((p) => p.slug !== current.slug && (p.category === current.category || p.destinationSlug === current.destinationSlug))
    .concat(packages.filter((p) => p.slug !== current.slug && p.category !== current.category && p.destinationSlug !== current.destinationSlug))
    .slice(0, limit);
}
